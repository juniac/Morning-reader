import AppKit
import Account
import RSCore
import UniformTypeIdentifiers

/// Lets the user pick an account and check the feeds to write to an OPML file.
/// Folders are kept in the file for the feeds that were chosen.
@MainActor final class ExportSubscriptionsController: NSObject {

  private struct FeedPlacement {
    let feed: Feed
    let folder: Folder?
  }

  private let hostWindow: NSWindow
  private let presenter: SubscriptionSheetPresenter
  private var sheetWindow: NSWindow?
  private var feedPlacements = [FeedPlacement]()

  private let accountPopUpButton = NSPopUpButton()
  private let checklistView = FeedChecklistView()
  private lazy var exportButton = NSButton(title: NSLocalizedString("Export…", comment: "Export subscriptions"), target: self, action: #selector(exportSelectedFeeds(_:)))

  init(hostWindow: NSWindow) {
    self.hostWindow = hostWindow
    self.presenter = SubscriptionSheetPresenter(hostWindow: hostWindow)
  }

  // MARK: - API

  func start() {
    let window = makeSheetWindow()
    sheetWindow = window
    presenter.present(window)
  }

  // MARK: - Actions

  @objc private func accountDidChange(_ sender: Any?) {
    reloadRows()
  }

  @objc private func cancel(_ sender: Any?) {
    endSheet(.cancel)
  }

  @objc private func exportSelectedFeeds(_ sender: Any?) {
    guard let account = selectedAccount() else {
      return
    }
    let selectedFeeds = Set(checklistView.selectedIndexes.map { feedPlacements[$0].feed })
    AppDefaults.exportOPMLAccountID = account.accountID
    endSheet(.OK)
    runSavePanel(account: account, selectedFeeds: selectedFeeds)
  }

  // MARK: - OPML

  /// Feed's ordering is internal to the Account module, so sort by display name here.
  static func sortedByName(_ feeds: Set<Feed>) -> [Feed] {
    feeds.sorted { $0.nameForDisplay.localizedStandardCompare($1.nameForDisplay) == .orderedAscending }
  }

  static func opmlString(account: Account, selectedFeeds: Set<Feed>, title: String) -> String {
    var body = ""
    for feed in sortedByName(account.topLevelFeeds) where selectedFeeds.contains(feed) {
      body += feed.OPMLString(indentLevel: 1, allowCustomAttributes: false)
    }
    for folder in account.sortedFolders ?? [] {
      let feeds = sortedByName(folder.topLevelFeeds).filter { selectedFeeds.contains($0) }
      guard !feeds.isEmpty else {
        continue
      }
      let escapedName = folder.nameForDisplay.escapingSpecialXMLCharacters
      body += "\t<outline text=\"\(escapedName)\" title=\"\(escapedName)\">\n"
      for feed in feeds {
        body += feed.OPMLString(indentLevel: 2, allowCustomAttributes: false)
      }
      body += "\t</outline>\n"
    }

    return """
    <?xml version="1.0" encoding="UTF-8"?>
    <!-- OPML generated by NetNewsWire -->
    <opml version="1.1">
    \t<head>
    \t\t<title>\(title.escapingSpecialXMLCharacters)</title>
    \t</head>
    \t<body>
    \(body)\t</body>
    </opml>

    """
  }
}

// MARK: - Private

private extension ExportSubscriptionsController {

  func makeSheetWindow() -> NSWindow {
    let window = NSWindow(contentRect: NSRect(x: 0, y: 0, width: presenter.preferredWidth, height: 480), styleMask: [.titled], backing: .buffered, defer: false)
    window.title = NSLocalizedString("Export Subscriptions", comment: "Export subscriptions")

    configureAccountPopUpButton()
    let accountLabel = NSTextField(labelWithString: NSLocalizedString("Account:", comment: "Export subscriptions"))
    let accountRow = NSStackView(views: [accountLabel, accountPopUpButton])
    accountPopUpButton.widthAnchor.constraint(greaterThanOrEqualToConstant: 240).isActive = true

    checklistView.selectionDidChange = { [weak self] in
      self?.updateExportButton()
    }

    let cancelButton = NSButton(title: NSLocalizedString("Cancel", comment: "Export subscriptions"), target: self, action: #selector(cancel(_:)))
    cancelButton.keyEquivalent = "\u{1b}"
    exportButton.keyEquivalent = "\r"
    let buttonRow = NSStackView()
    buttonRow.addView(cancelButton, in: .trailing)
    buttonRow.addView(exportButton, in: .trailing)

    let contentStack = NSStackView(views: [accountRow, checklistView, buttonRow])
    contentStack.orientation = .vertical
    contentStack.alignment = .leading
    contentStack.spacing = 12
    contentStack.edgeInsets = NSEdgeInsets(top: 20, left: 20, bottom: 20, right: 20)
    window.contentView = contentStack
    // ponytail: NSStackView's .width alignment did not stretch the checklist, so pin each row's width by hand.
    for arrangedView in contentStack.arrangedSubviews {
      arrangedView.widthAnchor.constraint(equalTo: contentStack.widthAnchor, constant: -40).isActive = true
    }

    reloadRows()
    return window
  }

  func configureAccountPopUpButton() {
    for account in AccountManager.shared.sortedAccounts {
      let item = NSMenuItem(title: account.nameForDisplay, action: nil, keyEquivalent: "")
      item.representedObject = account
      accountPopUpButton.menu?.addItem(item)
      if account.accountID == AppDefaults.exportOPMLAccountID {
        accountPopUpButton.select(item)
      }
    }
    accountPopUpButton.target = self
    accountPopUpButton.action = #selector(accountDidChange(_:))
  }

  func selectedAccount() -> Account? {
    accountPopUpButton.selectedItem?.representedObject as? Account
  }

  func reloadRows() {
    guard let account = selectedAccount() else {
      feedPlacements = []
      checklistView.rows = []
      return
    }
    var placements = Self.sortedByName(account.topLevelFeeds).map { FeedPlacement(feed: $0, folder: nil) }
    for folder in account.sortedFolders ?? [] {
      placements += Self.sortedByName(folder.topLevelFeeds).map { FeedPlacement(feed: $0, folder: folder) }
    }
    feedPlacements = placements
    checklistView.rows = placements.map { FeedChecklistRow(title: $0.feed.nameForDisplay, folderName: $0.folder?.nameForDisplay, url: $0.feed.url) }
  }

  func updateExportButton() {
    exportButton.isEnabled = selectedAccount() != nil && checklistView.hasSelection
  }

  func runSavePanel(account: Account, selectedFeeds: Set<Feed>) {
    let panel = NSSavePanel()
    panel.allowedContentTypes = [UTType.opml]
    panel.allowsOtherFileTypes = false
    panel.prompt = NSLocalizedString("Export OPML", comment: "Export subscriptions")
    panel.nameFieldLabel = NSLocalizedString("Export to:", comment: "Export subscriptions")
    panel.message = NSLocalizedString("Choose a location for the exported OPML file.", comment: "Export subscriptions")
    panel.isExtensionHidden = false

    let accountName = account.nameForDisplay.replacingOccurrences(of: " ", with: "")
    panel.nameFieldStringValue = "Subscriptions-\(accountName).opml"

    panel.beginSheetModal(for: hostWindow) { response in
      guard response == .OK, let url = panel.url else {
        return
      }
      let fileName = url.lastPathComponent
      do {
        try account.logActivity(kind: .exportOPML, detail: fileName) {
          let opml = Self.opmlString(account: account, selectedFeeds: selectedFeeds, title: fileName)
          try opml.write(to: url, atomically: true, encoding: .utf8)
        }
      } catch {
        NSApplication.shared.presentError(error)
      }
    }
  }

  func endSheet(_ response: NSApplication.ModalResponse) {
    guard let sheetWindow else {
      return
    }
    presenter.dismiss(sheetWindow, response: response)
    self.sheetWindow = nil
  }
}
